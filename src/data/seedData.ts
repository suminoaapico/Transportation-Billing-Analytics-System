function buildRateCardRows(truckType: StandardTruckType): RateCardRow[] {
  return STANDARD_26_RATE_CARD_LOCATIONS.map((loc, idx) => {
    let base = loc.base4W;
    let step = loc.step4W;

    if (truckType === '6W') {
      base = loc.base6W;
      step = loc.step6W;
    } else if (truckType === '10W') {
      base = loc.base10W;
      step = loc.step10W;
    } else if (truckType === 'OD4') {
      base = Math.round((loc.base4W * 1.15) / 10) * 10;
      step = Math.round((loc.step4W * 1.15) / 10) * 10;
    } else if (truckType === 'OD6') {
      base = Math.round((loc.base6W * 1.10) / 10) * 10;
      step = Math.round((loc.step6W * 1.10) / 10) * 10;
    }

    const rates: { [key: string]: number } = {};

    RATE_CARD_BRACKETS.forEach((bracket, bIdx) => {
      rates[bracket.key] = base + bIdx * step;
    });

    return {
      id: `rc-${truckType.toLowerCase()}-${idx + 1}`,
      location: loc.location,
      province: loc.province,
      region: loc.region,
      rates,
    };
  });
}

